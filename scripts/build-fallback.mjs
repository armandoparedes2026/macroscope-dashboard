// Node 22+, no dependencies. Run from any directory: node scripts/build-fallback.mjs
import { writeFile, mkdir, readFile } from 'node:fs/promises';
await import('../js/config/countries.js');
await import('../js/config/indicators.js');
await import('../js/data/fallback-wdi.js');
const { COUNTRIES, INDICATORS, FALLBACK_FX } = globalThis.MacroScope;
const extractedAt = new Date().toISOString();
const endYear = new Date().getUTCFullYear() - 1;
const years = Array.from({length:endYear-2013},(_,i)=>String(2014+i));
const db = {}, statuses = {}, indicators = {};
for (const country of Object.keys(COUNTRIES)) { db[country]={}; statuses[country]={}; }
async function get(url) {
  for(let attempt=0;attempt<4;attempt++) {
    try {
      const response = await fetch(url,{signal:AbortSignal.timeout(60000)});
      if(!response.ok) throw Error(`HTTP ${response.status}: ${url}`);
      const data=await response.json();
      if(!Array.isArray(data)||!data[0]||!Array.isArray(data[1])) throw Error(`Invalid WDI response: ${url}`);
      return data;
    } catch(error) { if(attempt===3)throw error; await new Promise(r=>setTimeout(r,1000*2**attempt)); }
  }
}
for (const code of Object.keys(INDICATORS)) {
  const apiUrl=`https://api.worldbank.org/v2/country/${Object.keys(COUNTRIES).join(';')}/indicator/${code}?date=2014:${endYear}&format=json&per_page=100`;
  const definitionUrl=`https://api.worldbank.org/v2/indicator/${code}?format=json`;
  const definition=(await get(definitionUrl))[1].find(row=>row.id===code);
  if(!definition)throw Error(`Missing definition: ${code}`);
  for(const country of Object.keys(COUNTRIES)) {
    db[country][code]=Object.fromEntries(years.map(y=>[y,null]));
    statuses[country][code]=Object.fromEntries(years.map(y=>[y,null]));
  }
  let pages=1; const lastupdated=[];
  for(let page=1;page<=pages;page++) {
    const [meta,rows]=await get(`${apiUrl}&page=${page}`);
    if(Number(meta.page)!==page||!Number.isInteger(Number(meta.pages))||Number(meta.pages)<1)throw Error('Invalid pagination');
    if(page>1&&Number(meta.pages)!==pages)throw Error('Pagination changed during extraction');
    pages=Number(meta.pages); lastupdated.push(meta.lastupdated??null);
    for(const row of rows) {
      if(!db[row.countryiso3code]||row.indicator?.id!==code||!years.includes(row.date)||!(row.value===null||Number.isFinite(row.value)))throw Error('Invalid observation');
      db[row.countryiso3code][code][row.date]=row.value;
      statuses[row.countryiso3code][code][row.date]=row.obs_status??null;
    }
  }
  indicators[code]={apiUrl,definitionUrl,lastupdated:[...new Set(lastupdated)],pages,definition};
  console.log(`${code}: ${pages} pages`);
}
const metadata={extractedAt,source:'WDI',period:`2014:${endYear}`,indicators};
const output=`// GENERATED by scripts/build-fallback.mjs. Do not edit observations.\n(function () {\n  'use strict';\n  const M = globalThis.MacroScope ||= {};\n  Object.assign(M, ${JSON.stringify({FALLBACK_DB:db,FALLBACK_OBS_STATUS:statuses,FALLBACK_METADATA:metadata,FALLBACK_EXTRACTED_AT:Object.fromEntries(Object.keys(INDICATORS).map(c=>[c,extractedAt])),FALLBACK_FX},null,2)});\n})();\n`;
await writeFile(new URL('../js/data/fallback-wdi.js',import.meta.url),output);
const esc=s=>String(s??'').replaceAll('|','\\|').replaceAll('\n',' ');
let doc=`# Fuentes y transformaciones WDI\n\nExtracción: **${extractedAt}**. Fuente: World Development Indicators (API v2). Periodo solicitado: 2014–${endYear}; frecuencia anual. Regenerar con Node 22: \`node scripts/build-fallback.mjs\`. Se recorren todas las páginas; se preservan null y obs_status sin redondear, interpolar ni sustituir por cero. lastupdated es la fecha del proveedor, distinta de extractedAt, y se conserva por indicador en FALLBACK_METADATA. Las cotizaciones FX anteriores son un respaldo referencial separado y no provienen de WDI.\n\n| Código | Nombre y definición oficial WDI | Unidad | Frecuencia | Transformación | Extracción / última revisión WDI |\n|---|---|---|---|---|---|\n`;
for(const [code,meta]of Object.entries(indicators))doc+=`| [${code}](${meta.definitionUrl}) | ${esc(meta.definition.name)}. ${esc(meta.definition.sourceNote)} | ${esc(INDICATORS[code].unit)} | Anual | Ninguna en el respaldo | ${extractedAt}; ${meta.lastupdated.join(', ')} |\n`;
doc+='\n## Cobertura por economía e indicador\n\nCuenta observaciones finitas en el periodo solicitado; último año con dato real. Los años ausentes permanecen null.\n\n| Economía | Indicador | Cobertura | Último año | Años sin dato |\n|---|---|---|---|---|\n';
for(const [country,series]of Object.entries(db))for(const [code,values]of Object.entries(series)) {
 const available=years.filter(y=>Number.isFinite(values[y]));
 doc+=`| ${country} — ${COUNTRIES[country].name} | ${code} | ${available.length}/${years.length} | ${available.at(-1)??'sin dato'} | ${years.filter(y=>!Number.isFinite(values[y])).join(', ')||'ninguno'} |\n`;
}
doc+=await readFile(new URL('./wdi-methodology.md',import.meta.url),'utf8');
await mkdir(new URL('../docs/',import.meta.url),{recursive:true});
await writeFile(new URL('../docs/fuentes-wdi.md',import.meta.url),doc);
